function attempt(
  n: number,
  minsAgo: number,
  responseCode: number | null,
  latencyMs: number | null,
  error: string | null,
) {
  return {
    attemptNumber: n,
    responseCode,
    latencyMs,
    error,
    attemptedAt: minutesAgo(minsAgo),
  };
}

